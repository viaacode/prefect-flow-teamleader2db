import os
import signal
import webbrowser
from contextlib import asynccontextmanager
from random import choices
from string import ascii_lowercase, digits
from typing import Optional

import requests
from fastapi import FastAPI
from pydantic.v1 import SecretStr
from requests import PreparedRequest

from flows.blocks.teamleader import TeamleaderCredentials

REDIRECT_URL = "https://127.0.0.1:8000/oauth"

####################
# Helper functions #
####################


def get_random_state():
    chars = choices(ascii_lowercase + digits, k=100)
    return "".join(chars)


async def open_authorization_url(state: str, tl_cred_name: str = "teamleader-credentials"):
    """
    Start the authorization flow by redirecting to the Teamleader authorization page
    as described in the [Teamleader documentation](https://developer.teamleader.eu/#/introduction/authentication/authorization-flow)
    """
    credentials = await TeamleaderCredentials.load(tl_cred_name)
    req = PreparedRequest()
    req.prepare_url(
        "https://focus.teamleader.eu/oauth2/authorize",
        {
            "client_id": credentials.client_id,
            "response_type": "code",
            "state": state,
            "redirect_uri": REDIRECT_URL,
        },
    )

    if req.url is None:
        raise ValueError("Could not create authorization url")

    print(f"\nOpen this URL in your webbrowser: \n\n{req.url}\n\n")
    webbrowser.open(req.url)


def get_access_token_from_teamleader(code: str, tl_cred_name: str = "teamleader-credentials"):
    """
    After the user has granted authorization through the webbrowser, an access code is requested from Teamleader.
    """
    credentials = TeamleaderCredentials.load(tl_cred_name)
    response = requests.post(
        "https://focus.teamleader.eu/oauth2/access_token",
        data={
            "client_id": credentials.client_id,
            "client_secret": credentials.client_secret.get_secret_value(),
            "code": code,
            "grant_type": "authorization_code",
            "redirect_uri": REDIRECT_URL,
        },
        timeout=60,
    )

    if response.status_code != 200:
        raise RuntimeError(f"Status code {response.status_code} - {response.reason}")

    return response.json()


###############
# Main script #
###############

"""
The user is immediately redirected to the Teamleader authorization page on server startup.
If the user grants authorization, Teamleader will redirect the user to a route
which will request the tokens and save the refresh token to the TeamleaderCredentials block.  

See https://developer.teamleader.eu/#/introduction/authentication for more info around authorization.
"""


global_state = {}


@asynccontextmanager
async def lifespan(_: FastAPI):
    global_state["state"] = get_random_state()
    await open_authorization_url(global_state["state"])
    yield


app = FastAPI(lifespan=lifespan)


@app.get("/oauth")
def authorize(
    code: Optional[str] = None,
    state: Optional[str] = None,
    error: Optional[str] = None,
    tl_cred_name: str = "teamleader-credentials"
):

    if error is not None:
        raise PermissionError(error)

    if code is None or state is None:
        return {"error": "Either code or state was not given."}

    if state != global_state["state"]:
        return {
            "error": "The state generated by this server and state returned from Teamleader do not match which might indicate tampering."
        }

    try:
        tokens = get_access_token_from_teamleader(code)
        credentials = TeamleaderCredentials.load(tl_cred_name)
        credentials.refresh_token = SecretStr(tokens["refresh_token"])
        credentials.save(tl_cred_name, overwrite=True)
    except (ConnectionError, RuntimeError, ValueError) as e:
        return {"error": str(e)}

    print("\n\nSuccess - fetched tokens from Teamleader and saved the refresh token to Prefect\n")
    os.kill(os.getpid(), signal.SIGTERM)
    return {"message": "Success - fetched tokens from Teamleader and saved the refresh token to Prefect"}


